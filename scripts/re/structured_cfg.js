// Structural analysis / AST construction
// ---------------------------------------------------------------------------

// The structural analyser walks a procedure's CFG and builds an AST of statements.
// Each statement node is one of:
//   {t:'seq', stmts:[...]}
//   {t:'inst', text}
//   {t:'if', cond, then:[...], else:[...]}
//   {t:'while', cond, body:[...]}
//   {t:'dowhile', cond, body:[...]}
//   {t:'switch', expr, cases:[{v, stmts}], def:[...]}
//   {t:'break'}, {t:'continue'}, {t:'goto', label}
//   {t:'label', name}
//   {t:'call', text}
//   {t:'ret'}, {t:'exit', text}
function structAnalyse(blocks, proc, ctx) {
  const { succsOf, ipdom, loops, loopHeaderOf } = ctx;
  const root = proc.root;
  const emitted = new Set(); // block ids rendered as straight-line/structural nodes
  const loopDone = new Set(); // loop headers whose while/do-while was emitted
  const gotoTargets = new Set(); // block ids that are actually targeted by an emitted `goto`

  const stmts = [];
  const line = (text) => ({ t: 'inst', text });

  function block(id) { return blocks[id]; }
  function labelName(bid) {
    const b = block(bid);
    if (b.labelNames.length) return b.labelNames[0];
    return `bb_${bid}`;
  }

  // Emit straight-line (non-control) instructions of a block.
  // `skip` (optional Set of insts) drops those instructions (used for the fold).
  function emitStraight(b, skip) {
    const out = [];
    const head = b.ctrl == null ? b.insts : b.insts.slice(0, -1);
    for (const inst of head) {
      if (skip && skip.has(inst)) continue;
      out.push(line(renderInst(inst)));
    }
    return out;
  }

  // Emit a call to an intra-script subroutine.
  function emitCall(b) {
    const last = b.ctrl;
    const name = blockNameForCall(b);
    if (last == null || last.mnem !== 'call') return [];
    return [line(`call ${name}(${last.args.slice(1).map(opName).join(', ')})`)];
  }

  function blockNameForCall(b) {
    if (b.callTarget != null) return labelName(b.callTarget);
    const t = b.ctrl.args[0];
    return t.startsWith('label_') ? t : t;
  }

  // The main recursive region emitter.
  // Walks from `entry`, generating statements, stopping when control reaches a
  // block in `exits` (those blocks are not consumed here; they are where the
  // enclosing structure resumes). `topLevel` controls whether block labels are
  // emitted: they are only shown at the procedure's top-level flow (as branch/merge
  // anchors), NOT inside if/else/while bodies.
  function emit(entry, exits, topLevel = false) {
    const out = [];
    let cur = entry;
    let guard = 0;
    while (cur != null && !exits.has(cur) && guard++ < 100000) {
      const b = block(cur);
      if (!b) { if (process.env.STRUCT_DEBUG) console.error(`  [debug] BAD cur=${cur} (exits=${[...exits]})`); out.push({ t: 'goto', label: `bb_${cur}` }); break; }
      // Loop header not yet emitted? loopHeaderOf maps a node to its innermost header.
      const loopHdr = loopHeaderOf && loopHeaderOf.get(cur);
      if (loopHdr != null && loops.has(loopHdr) && !loopDone.has(loopHdr) && cur === loopHdr) {
        const r = emitLoop(loopHdr, exits);
        out.push(r.node);
        loopDone.add(loopHdr);
        cur = r.next;
        continue;
      }
      if (emitted.has(cur)) { out.push({ t: 'goto', label: labelName(cur) }); break; }
      emitted.add(cur);

      // Label retention policy: every non-root block gets a `:`-anchor candidate at
      // the point it is emitted (using its label name, or `bb_N` for unnamed). A final
      // post-pass keeps ONLY the anchors that are actually referenced (by a `goto`, or
      // as a label operand of a retained instruction like `call`/`jmp`/`jcc`), so every
      // reference resolves while the many disassembler branch/merge markers that nothing
      // jumps to are dropped. The procedure root's label is its function name.
      if (cur !== root) {
        out.push({ t: 'label', name: labelName(cur) });
      }

      const ctrl = b.ctrl;
      if (ctrl == null) {
        out.push(...emitStraight(b));
        cur = b.follow;
        continue;
      }
      const m = ctrl.mnem;
      if (m === 'exit' || m === 'exit-script') {
        out.push(...emitStraight(b));
        out.push({ t: 'exit', text: m });
        cur = null; break;
      }
      if (m === 'ret') {
        out.push(...emitStraight(b));
        out.push({ t: 'ret' });
        cur = null; break;
      }
      if (m === 'call') {
        out.push(...emitStraight(b));
        out.push(...emitCall(b));
        cur = b.follow;
        continue;
      }
      if (m === 'jmp') {
        out.push(...emitStraight(b));
        const t = b.follow;
        if (t != null) {
          // A jmp to an un-emitted loop header is the natural loop entry -> fall into it.
          if (loops.has(t) && !loopDone.has(t) && !emitted.has(t)) {
            cur = t; continue;
          }
          // A jmp to an exit boundary -> drop it; the enclosing structure takes over.
          if (exits.has(t)) { cur = null; break; }
          const tb = block(t);
          // A single-predecessor target is a sequential continuation -> flatten (no goto).
          if (tb && tb.preds.size <= 1) { cur = t; continue; }
          gotoTargets.add(t);
          out.push({ t: 'goto', label: labelName(t) });
          cur = t;
          continue;
        }
        cur = null; break;
      }
      if (m === 'jcc') {
        // Fold the immediately-preceding assignment to the tested variable into the
        // if/while header (when present); keep all other instructions. Unexpected
        // shapes are left verbatim (recorded separately).
        const head = b.insts.slice(0, -1);
        const fold = findFoldable(b.ctrl, head);
        const skip = fold ? new Set([fold]) : null;
        out.push(...emitStraight(b, skip));
        const r = structureIfOrFallback(b, exits, fold);
        out.push(...r.stmts);
        cur = r.next;
        continue;
      }
    }
    return out;
  }

  // Try to structure the current block's jcc as if / if-else. Returns {stmts, next}.
  // `fold` (optional) is the instruction that assigns the tested variable and was
  // folded into the condition (its value/references preserved in the header).
  function structureIfOrFallback(b, exits, fold = null) {
    const br = b.branches;
    if (!br) return { stmts: [line(renderTerm(b.ctrl))], next: b.follow };
    const T = br.trueBlock;
    const F = br.falseBlock;
    const varStr = fold ? opName(fold.argsCls[0]) : condForJcc(b.ctrl);
    const rhs = fold ? symbolicRHS(fold) : null;
    const condBase = (rhs != null) ? `${varStr} = ${rhs}` : varStr;
    // Negated condition: keep showing the assignment, then the negated test variable.
    const negCondOf = () => (rhs != null) ? `${condBase}, not ${varStr}` : `not ${varStr}`;
    const join = ipdom.get(b.id);
    const joinReal = (join != null && join !== EXIT) ? join : null;
    const tTerm = T != null && (succsOf(T).length === 0);
    const fTerm = F != null && (succsOf(F).length === 0);

    // Early-return / early-exit: one branch terminates the procedure. Only apply
    // when there is no real reconvergence point (join === virtual EXIT); if a real
    // join exists the join-based rules already handle a terminal join correctly.
    if (joinReal == null && tTerm && !fTerm && F != null) {
      // cond true -> T (returns), cond false -> F (continues).
      const body = emit(T, new Set(), false);
      return { stmts: [{ t: 'if', cond: condBase, then: body, else: [] }], next: F };
    }
    if (joinReal == null && fTerm && !tTerm && T != null) {
      // cond true -> T (continues), cond false -> F (returns).
      const retElse = emit(F, new Set(), false);
      const body = emit(T, new Set(), false);
      return { stmts: [{ t: 'if', cond: condBase, then: body, else: retElse }], next: null };
    }

    // Deterministic join (real block): structure as if / if-else.
    const tIsJoin = joinReal != null && T === joinReal;
    const fIsJoin = joinReal != null && F === joinReal;

    const structureBody = (entryBlock) => {
      if (entryBlock == null) return { stmts: [], next: joinReal };
      const region = collectRegion(entryBlock, new Set([joinReal]).add(b.id), ctx.succsOf);
      if (!region.reachable) return { stmts: [], next: joinReal };
      const stmts = emit(entryBlock, new Set([joinReal]), false);
      return { stmts, next: joinReal };
    };

    if (tIsJoin && fIsJoin) {
      return { stmts: [{ t: 'if', cond: condBase, then: [], else: [] }], next: joinReal };
    }
    if (tIsJoin && !fIsJoin && F != null) {
      // cond true -> join (no-op), cond false -> body. => if (cond) {} else {F} == if(!cond){F}
      const body = structureBody(F);
      return { stmts: [{ t: 'if', cond: negCondOf(), then: body.stmts, else: [] }], next: body.next };
    }
    if (fIsJoin && !tIsJoin && T != null) {
      const body = structureBody(T);
      return { stmts: [{ t: 'if', cond: condBase, then: body.stmts, else: [] }], next: body.next };
    }
    if (!tIsJoin && !fIsJoin && T != null && F != null && joinReal != null) {
      // if/else, both branches reconverge at joinReal.
      const rT = collectRegion(T, new Set([joinReal]), ctx.succsOf);
      const rF = collectRegion(F, new Set([joinReal]), ctx.succsOf);
      if (rT.reachable && rF.reachable) {
        const thenS = emit(T, new Set([joinReal]), false);
        const elseS = emit(F, new Set([joinReal]), false);
        return { stmts: [{ t: 'if', cond: condBase, then: thenS, else: elseS }], next: joinReal };
      }
    }
    // Fallback: emit the block as a conditional branch with gotos, then fall through.
    return fallbackJcc(b, exits);
  }

  function fallbackJcc(b, exits) {
    const br = b.branches;
    const out = [line(renderTerm(b.ctrl))];
    // Represent both edges; fall-through continuation next.
    const next = b.follow;
    if (next != null) return { stmts: out, next };
    return { stmts: out, next: null };
  }

  function renderTerm(inst) {
    return renderInst(inst);
  }

  // Emit a loop whose header is `header`. Returns {node, next}.
  // When the loop's condition is a single assignment to the tested variable (foldable),
  // it is folded into a clean `while <var> = <expr>`. Otherwise a faithful two-step
  // form is used so the condition variable is recomputed each iteration (side-effects
  // preserved): `while true { <cond-computing stmts>; if not <var> break; <body> }`.
  function emitLoop(header, exits) {
    const loop = loops.get(header);
    const exitsSet = loopExits(blocks, loop, ctx.succsOf);
    // The condition block: the loop node whose jcc exits the loop.
    let condBlock = null;
    let condCtrl = null;
    for (const id of loop) {
      const b = block(id);
      const c = b.ctrl;
      if (c && c.mnem === 'jcc') {
        const t = b.branches.trueBlock;
        const f = b.branches.falseBlock;
        if ((t != null && exitsSet.has(t)) || (f != null && exitsSet.has(f))) {
          condBlock = id;
          condCtrl = c;
          break;
        }
      }
    }
    const head = condCtrl ? block(condBlock).insts.slice(0, -1) : [];
    const fold = condCtrl ? findFoldable(condCtrl, head) : null;
    const varStr = fold ? opName(fold.argsCls[0]) : (condCtrl ? condForJcc(condCtrl) : 'true');
    const rhs = fold ? symbolicRHS(fold) : null;
    const isWhile = condBlock != null && condBlock === header;
    // The loop-body entry: from the header's in-loop branch (the branch that stays in loop).
    let bodyEntry = null;
    const hb = block(header);
    const hc = hb.ctrl;
    if (hc && hc.mnem === 'jcc') {
      const t = hb.branches.trueBlock;
      const f = hb.branches.falseBlock;
      if (t != null && loop.has(t)) bodyEntry = t;
      else if (f != null && loop.has(f)) bodyEntry = f;
    }
    if (bodyEntry == null) {
      for (const s of ctx.succsOf(header)) if (loop.has(s)) { bodyEntry = s; break; }
    }
    const bodyExits = new Set([header, ...exitsSet]);
    const bodyStmts = (bodyEntry != null) ? emit(bodyEntry, bodyExits, false) : emitStraight(hb);

    let node;
    if (isWhile && fold && head.length === 1) {
      // Clean folded form: the assignment IS the loop condition (re-evaluated each pass).
      node = { t: 'while', cond: `${varStr} = ${rhs}`, body: bodyStmts };
    } else if (isWhile) {
      node = {
        t: 'while',
        cond: 'true',
        body: [
          ...head.map((i) => line(renderInst(i))),
          { t: 'if', cond: negCond(varStr), then: [{ t: 'break' }], else: [] },
          ...bodyStmts,
        ],
      };
    } else {
      // do-while (test at bottom); the body already carries the recompute just before
      // the back edge, so a plain `do { body } while <var>` is faithful.
      node = { t: 'dowhile', cond: varStr, body: bodyStmts };
    }
    let next = null;
    for (const e of exitsSet) { next = e; break; }
    return { node, next };
  }

  // Top-level: structure the procedure body. Label pruning is a global post-pass
  // over all procedures (see analyseFile) so cross-proc references resolve.
  return emit(root, new Set(), true);
}

// Children of a statement node (for AST traversal).
function stmtChildren(node) {
  switch (node.t) {
    case 'seq': return node.stmts;
    case 'if': return [...node.then, ...node.else];
    case 'while': case 'dowhile': return node.body;
    case 'switch': return [...node.cases.map((c) => c.stmts).flat(), ...node.def];
    default: return [];
  }
}

// Collect the set of label names that are actually referenced: every `goto` target and
// every label that appears as an operand of a retained instruction (e.g. `call label_X`,
// a raw `jmp`/`jcc` that was left in the fallback).
function collectLabelRefs(node, set) {
  if (node.t === 'goto') set.add(node.label);
  else if ((node.t === 'inst' || node.t === 'call') && node.text) {
    const m = /label_[0-9A-Fa-f]+/.exec(node.text);
    if (m) set.add(m[0]);
  }
  for (const c of stmtChildren(node)) collectLabelRefs(c, set);
  return set;
}

// Remove `label:` anchors that nothing references. `refs` is the set of referenced
// label names collected across ALL procedures (so cross-proc references keep anchors).
// `stmts` is the top-level statement ARRAY returned by `emit`.
function pruneUnreferencedLabels(stmts, refs) {
  const cut = (n) => n.t === 'label' && !refs.has(n.name);
  const prune = (n) => {
    if (cut(n)) return null;
    if (n.t === 'seq') n.stmts = n.stmts.map(prune).filter(Boolean);
    else if (n.t === 'if') { n.then = n.then.map(prune).filter(Boolean); n.else = n.else.map(prune).filter(Boolean); }
    else if (n.t === 'while' || n.t === 'dowhile') n.body = n.body.map(prune).filter(Boolean);
    else if (n.t === 'switch') { n.cases = n.cases.map((c) => ({ ...c, stmts: c.stmts.map(prune).filter(Boolean) })); n.def = n.def.map(prune).filter(Boolean); }
    return n;
  };
  const pruned = [];
  for (const n of stmts) {
    if (cut(n)) continue;
    const r = prune(n);
    if (r) pruned.push(r);
  }
  stmts.length = 0;
  stmts.push(...pruned);
}

// Attach ctrl metadata to every block based on its last instruction.
function attachCtrl(blocks) {
  for (const b of blocks) {
    const last = b.insts[b.insts.length - 1];
    b.ctrl = last && TERMINATORS.has(last.mnem) ? last : null;
  }
}

