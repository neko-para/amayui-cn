function nodeLabel(b) {
  const names = (b.labelNames && b.labelNames.length) ? b.labelNames.join(',') : `bb_${b.id}`;
  return names;
}

function toDot(blocks, proc, edges) {
  const all = proc ? new Set(proc.blockIds || proc.members || []) : null;
  const lines = ['digraph CFG {'];
  lines.push('  rankdir=TB;');
  lines.push('  node [shape=box, fontname="monospace"];');
  for (const b of blocks) {
    if (all && !all.has(b.id)) continue;
    const body = b.insts.map(i => renderInst(i)).join('\\l');
    lines.push(`  n${b.id} [label="${nodeLabel(b)}\\l${body}\\l"];`);
  }
  for (const b of blocks) {
    if (all && !all.has(b.id)) continue;
    for (const s of b.succs) {
      if (all && !all.has(s)) continue;
      const lbl = b.branches && b.branches.trueBlock === s ? 'T' : (b.branches && b.branches.falseBlock === s ? 'F' : '');
      lines.push(`  n${b.id} -> n${s}${lbl ? ` [label="${lbl}"]` : ''};`);
    }
  }
  lines.push('}');
  return lines.join('\n');
}

