// ---------------------------------------------------------------------------
// CFG procedure extraction
// ---------------------------------------------------------------------------

function extractProcedures(blocks, entry, succsOf) {
  const inProc = new Array(blocks.length).fill(-1);
  const roots = [entry];
  // Add call-target blocks that are not part of main as subroutine roots.
  for (const b of blocks) {
    if (b.callTarget != null) roots.push(b.callTarget);
  }
  const procs = [];
  const assign = (root) => {
    if (inProc[root] >= 0) return inProc[root];
    const id = procs.length;
    const members = [];
    const visited = new Set();
    const work = [root];
    visited.add(root);
    while (work.length) {
      const x = work.pop();
      members.push(x);
      inProc[x] = id;
      for (const s of succsOf(x)) {
        if (!visited.has(s)) { visited.add(s); work.push(s); }
      }
    }
    procs.push({ root, members });
    return id;
  };
  for (const r of roots) assign(r);
  // Any block not covered (e.g., lone dead code) gets its own procedure.
  for (let i = 0; i < blocks.length; i++) if (inProc[i] < 0) assign(i);
  return { procs, inProc };
}

