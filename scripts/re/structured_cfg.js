// Return a single `if` node if the statement list is exactly one if (possibly wrapped
// in a one-element seq), otherwise null. Used to fold `else { if }` -> `else if`.
function foldElseIf(stmts) {
  if (stmts.length === 1) {
    let s = stmts[0];
    if (s.t === 'seq' && s.stmts.length === 1) s = s.stmts[0];
    if (s.t === 'if') return s;
  }
  return null;
}

// Render an `else if <cond> ...` node at the given indentation, continuing the fold.
function renderElseIf(node, out, indent) {
  const pad = '    '.repeat(indent);
  out.push(`${pad}else if ${node.cond}`);
  if (node.then.length) render({ t: 'seq', stmts: node.then }, out, indent + 1);
  if (node.else.length) {
    const folded = foldElseIf(node.else);
    if (folded != null) renderElseIf(folded, out, indent);
    else {
      out.push(pad + 'else');
      render({ t: 'seq', stmts: node.else }, out, indent + 1);
    }
  }
}

function render(node, out, indent) {
  const pad = '    '.repeat(indent);
  switch (node.t) {
    case 'seq':
      for (const s of node.stmts) render(s, out, indent);
      break;
    case 'inst':
      out.push(pad + node.text);
      break;
    case 'if':
      out.push(`${pad}if ${node.cond}`);
      if (node.then.length) render({ t: 'seq', stmts: node.then }, out, indent + 1);
      if (node.else.length) {
        // Fold `else { if ... }` into `else if ...` to reduce nesting in if/else-if chains.
        const folded = foldElseIf(node.else);
        if (folded != null) {
          renderElseIf(folded, out, indent);
        } else {
          out.push(pad + 'else');
          render({ t: 'seq', stmts: node.else }, out, indent + 1);
        }
      }
      break;
    case 'while':
      out.push(`${pad}while ${node.cond}`);
      if (node.body.length) render({ t: 'seq', stmts: node.body }, out, indent + 1);
      break;
    case 'dowhile':
      out.push(`${pad}do`);
      if (node.body.length) render({ t: 'seq', stmts: node.body }, out, indent + 1);
      out.push(`${pad}while ${node.cond}`);
      break;
    case 'switch':
      out.push(`${pad}switch ${node.expr}`);
      for (const c of node.cases) {
        out.push(`${pad}    case ${c.v}`);
        render({ t: 'seq', stmts: c.stmts }, out, indent + 2);
      }
      if (node.def.length) {
        out.push(`${pad}    default`);
        render({ t: 'seq', stmts: node.def }, out, indent + 2);
      }
      break;
    case 'break':
      out.push(pad + 'break');
      break;
    case 'continue':
      out.push(pad + 'continue');
      break;
    case 'goto':
      out.push(pad + `goto ${node.label}`);
      break;
    case 'label':
      out.push(pad + `${node.name}:`);
      break;
    case 'call':
      out.push(pad + node.text);
      break;
    case 'ret':
      out.push(pad + 'ret');
      break;
    case 'exit':
      out.push(pad + (node.text || 'exit'));
      break;
    default:
      out.push(pad + JSON.stringify(node));
  }
}

