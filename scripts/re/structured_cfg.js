function options(raw) {
  const opts = { files: [], dot: null, json: null, raw: false, dir: null, out: '.', suffix: '.struct.txt' };
  for (let i = 0; i < raw.length; i++) {
    const a = raw[i];
    if (a === '--dot') opts.dot = raw[++i];
    else if (a === '--json') opts.json = raw[++i];
    else if (a === '--raw') opts.raw = true;
    else if (a === '--dir') opts.dir = raw[++i];
    else if (a === '--out') opts.out = raw[++i];
    else if (a === '--suffix') opts.suffix = raw[++i];
    else if (a === '--help' || a === '-h') opts.help = true;
    else if (a.startsWith('-')) { /* ignore unknown flags */ }
    else opts.files.push(a);
  }
  return opts;
}

function analyseFile(file, opts) {
  const t0 = process.hrtime.bigint();
  CURRENT_FILE = file;
  const text = fs.readFileSync(file, 'utf8');
  const sc = parse(text);
  const tParse = (process.hrtime.bigint() - t0) / 1000000n;
  const { blocks, blockOfInstr } = buildBlocks(sc);
  attachCtrl(blocks);
  const succsOf = (id) => [...(blocks[id].succs)];
  const tBlocks = (process.hrtime.bigint() - t0) / 1000000n - tParse;
  if (process.env.STRUCT_TIMING) console.error(`  [timing] ${path.basename(file)} insts=${sc.insts.length} blocks=${blocks.length} build=${tBlocks}ms`);

  const { procs, inProc } = extractProcedures(blocks, 0, succsOf);
  const ctx = { blocks, succsOf, labelOf: sc.labelOf };

  const procResults = [];
  for (const proc of procs) {
    const nodes = proc.members;
    const entry = proc.root;
    const domInfo = computeDominators(nodes, entry, succsOf);
    const post = computePostdominators(nodes, succsOf);
    const ipdom = post.ipdom;
    if (process.env.STRUCT_TIMING) console.error(`  [timing] ${path.basename(file)} insts=${sc.insts.length} blocks=${blocks.length} proc=${proc.root} nodes=${nodes.length}`);
    const loops = findNaturalLoops(blocks, entry, succsOf, domInfo);
    if (process.env.STRUCT_DEBUG) {
      console.error(`  [debug] proc root=${entry} nodes=${nodes.join(',')}`);
      for (const [h, l] of loops) console.error(`  [debug]   loop header=${h} members=${[...l].join(',')}`);
    }
    // loopHeaderOf: node -> header of the innermost loop containing it.
    const loopHeaderOf = new Map();
    for (const [hdr, loop] of loops) for (const id of loop) {
      const cur = loopHeaderOf.get(id);
      if (cur == null || loop.size < (loops.get(cur)?.size || Infinity)) loopHeaderOf.set(id, hdr);
    }
    const pctx = { ...ctx, ipdom, loops, loopHeaderOf };
    const stmts = structAnalyse(blocks, proc, pctx);
    procResults.push({ root: entry, blockIds: nodes, stmts });
  }

  // Label retention, GLOBAL pass: a `call`/`goto`/`jcc` in one procedure can reference
  // a block that lives in another procedure (or is flow-reachable there). So we collect
  // references across ALL procedures, then keep a label anchor only if something
  // (anywhere) references it. This makes cross-proc references resolve.
  const globalRefs = new Set();
  for (const p of procResults) collectLabelRefs({ t: 'seq', stmts: p.stmts }, globalRefs);
  for (const p of procResults) pruneUnreferencedLabels(p.stmts, globalRefs);

  // References completeness: any referenced label that got no anchor / proc (its block
  // was dropped by a fallback branch) is surfaced as a stub section, so `call`/`jcc`
  // references always have a visible target. Only emit the section if there are such.
  const defined = new Set();
  for (const p of procResults) {
    if (p.isStub) continue;
    const rb = blocks[p.root];
    if (rb) for (const n of rb.labelNames) defined.add(n); // procedure name (function boundary)
  }
  for (const p of procResults) collectLabelNodes({ t: 'seq', stmts: p.stmts }, defined); // shown anchors
  const stubs = [];
  for (const lab of globalRefs) {
    if (defined.has(lab)) continue;
    const iidx = sc.labelOf.get(lab);
    if (iidx == null || iidx >= blockOfInstr.length || blockOfInstr[iidx] == null) continue;
    const bid = blockOfInstr[iidx];
    const b = blocks[bid];
    const body = b.insts.map((i) => line0(renderInst(i)));
    stubs.push({ t: 'label', name: lab });
    stubs.push(...body);
    stubs.push({ t: 'ret' });
    defined.add(lab);
  }
  if (stubs.length) procResults.push({ root: -1, blockIds: [], stmts: stubs, isStub: true });

  return { file, sc, blocks, procs: procResults };
}

function collectLabelNodes(node, set) {
  if (node.t === 'label') set.add(node.name);
  for (const c of stmtChildren(node)) collectLabelNodes(c, set);
}

const line0 = (text) => ({ t: 'inst', text });

function renderProcedure(proc) {
  const out = [];
  render({ t: 'seq', stmts: proc.stmts }, out, 0);
  return out;
}

function main() {
  const opts = options(process.argv.slice(2));
  if (opts.help) {
    console.log(`Usage:
  node re/structured_cfg.js <src.txt> [--dot out.dot] [--json out.json] [--raw]
  node re/structured_cfg.js --dir <srcdir> [--out <dir>] [--suffix .struct.txt]`);
    process.exit(0);
  }
  let files = opts.files;
  if (opts.dir) {
    files = fs.readdirSync(opts.dir).filter(f => f.endsWith('.txt')).map(f => path.join(opts.dir, f)).sort();
  }
  if (files.length === 0) { console.error('No input files.'); process.exit(1); }

  for (const file of files) {
    try {
      const res = analyseFile(file, opts);
      if (opts.dot) {
        const dot = toDot(res.blocks, res.procs[0], null);
        fs.writeFileSync(opts.dot, dot);
        console.log(`# dot -> ${opts.dot}`);
      }
      if (opts.json) {
        fs.writeFileSync(opts.json, JSON.stringify({
          file: file,
          procedures: res.procs.map(p => ({ root: p.root, blocks: p.blockIds, stmts: p.stmts })),
        }, null, 2));
        console.log(`# json -> ${opts.json}`);
      }
      // Render each procedure.
      const outLines = [];
      outLines.push(`;; ${path.basename(file)}`);
      outLines.push(`;; local_vars = ${JSON.stringify(res.sc.locals || [])}`);
      for (const p of res.procs) {
        if (p.isStub) {
          outLines.push(';; --- referenced targets not reachable in structure (stubs) ---');
          outLines.push(...renderProcedure(p));
          outLines.push('');
          continue;
        }
        outLines.push(`;; --- procedure root=bb_${p.root} (${res.blocks[p.root].labelNames.join(',') || 'entry'}) ---`);
        outLines.push(...renderProcedure(p));
        outLines.push('');
      }
      const text = outLines.join('\n');
      if (opts.dir && opts.out) {
        const base = path.basename(file, path.extname(file));
        const dest = path.join(opts.out, base + opts.suffix);
        fs.writeFileSync(dest, text);
        console.log(`# -> ${dest}`);
      } else {
        console.log(text);
      }
    } catch (e) {
      console.error(`!! ${file}: ${e.message}`);
      if (process.env.STRUCT_DEBUG) console.error(e.stack);
    }
  }

  if (unexpected.size) {
    console.error(`\n[record] ${unexpected.size} instruction shape(s) kept VERBATIM (not rewritten):`);
    for (const [key, info] of unexpected) {
      console.error(`  ${info.count}x  ${key}   e.g. ${info.example}   (${info.file})`);
    }
  }
}

main();
