#!/usr/bin/env node
// structured_cfg.js
//
// Reconstruct a structured-pseudocode view of an AGE-engine disassembled script
// (src/*.txt). Pipeline:
//
//   1. Parse the disassembly text into instructions, resolving `label_XXXX` names
//      to instruction indexes.
//   2. Split into basic blocks at every control-flow boundary (jump/jump-cond/call
//      targets AND immediately after each control instruction) and build the
//      control-flow graph (CFG).
//   3. Compute dominators / postdominators (iterative fixpoint) and detect natural
//      loops from back edges.
//   4. Structurally analyse the reducible CFG (the AGE bytecode is compiler output,
//      so the overwhelming majority of scripts are reducible) into an AST of
//      sequences / if / if-else / while / do-while, with `break`/`continue`/`goto`
//      fallback for whatever does not fit a schema.
//   5. Pretty-print the AST as readable pseudocode (or emit DOT / JSON for the CFG).
//
// The AGE `jcc` is a two-target conditional jump:
//     jcc cond A B   ->  if (cond != 0) { if A != ffffffff goto A; else fallthrough }
//                         else          { if B != ffffffff goto B; else fallthrough }
// `0xFFFFFFFF` means "this branch does not jump / falls through". `jmp L` = goto L.
//
// Because the engine's bytecode is generated by a compiler, the CFGs are almost
// always reducible and structure cleanly into if/while. Anything that does not
// cleanly reduce is emitted as an explicit `label:`+`goto` so the output is always
// a faithful, valid rendering of the original flow.
//
// Usage:
//   node re/structured_cfg.js <src-file.txt> [--dot out.dot] [--json out.json] [--raw]
//   node re/structured_cfg.js --dir src [--out output/ --suffix .struct.txt]
//
// Exit codes: 0 ok, 1 bad args / parse failure, 2 unrecoverable error.

import fs from 'node:fs';
import path from 'node:path';

// ---------------------------------------------------------------------------
// Tokenizing & instruction parsing
// ---------------------------------------------------------------------------

// Strip `// line comments` and `/* block */` comments, but not ones inside "..." strings.
function stripComments(s) {
  let out = '';
  let inStr = false;
  let inBlock = false;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    const n = s[i + 1];
    if (inBlock) {
      if (c === '*' && n === '/') { inBlock = false; i++; }
      continue;
    }
    if (inStr) {
      out += c;
      if (c === '"') inStr = false;
      continue;
    }
    if (c === '"') { inStr = true; out += c; continue; }
    if (c === '/' && n === '*') { inBlock = true; i++; continue; }
    if (c === '/' && n === '/') break; // line comment to end
    out += c;
  }
  return out;
}

// Split a line into tokens. Parenthesised groups `( x y )` and double-quoted
// strings are kept as single tokens; otherwise whitespace separates tokens.
function tokenize(s) {
  s = stripComments(s).trim();
  const toks = [];
  let i = 0;
  while (i < s.length) {
    while (i < s.length && /\s/.test(s[i])) i++;
    if (i >= s.length) break;
    let cur = '';
    const c0 = s[i];
    if (c0 === '(') {
      let depth = 0;
      while (i < s.length) {
        const c = s[i];
        cur += c;
        if (c === '(') depth++;
        else if (c === ')') { depth--; if (depth === 0) { i++; break; } }
        i++;
      }
    } else if (c0 === '"') {
      cur = '"';
      i++;
      while (i < s.length && s[i] !== '"') { cur += s[i]; i++; }
      cur += '"';
      i++;
      // If there is no closing quote, still accept what we have (tolerant).
      if (s[i - 1] !== '"') cur += '"';
    } else {
      while (i < s.length && !/\s/.test(s[i])) { cur += s[i]; i++; }
    }
    toks.push(cur);
  }
  return toks;
}

function isHeaderLine(line) {
  const t = line.trim();
  return t.startsWith('==') || t.startsWith('signature') || t.startsWith('local_vars');
}

// Unpack a token into {kind, ...} for easier handling.
// Kinds: local (int/ptr/string), global (int/ptr/string), imm (number/hex),
//        label, immstr, rawword.
function classify(tok) {
  if (tok.startsWith('label_')) return { kind: 'label', name: tok };
  let m = /^\(local-(int|ptr|string|float-ptr|float) ([0-9a-fA-F]+)\)$/.exec(tok);
  if (m) return { kind: 'local', type: m[1], idx: parseInt(m[2], 16) };
  m = /^\(global-(int|ptr|string|float-ptr|float) ([0-9a-fA-F]+)\)$/.exec(tok);
  if (m) return { kind: 'global', type: m[1], idx: parseInt(m[2], 16) };
  if (tok.startsWith('"')) return { kind: 'str', raw: tok };
  if (/^0x[0-9a-fA-F]+$/.test(tok)) return { kind: 'imm', raw: tok, val: parseInt(tok, 16) };
  if (/^[0-9a-fA-F]+$/.test(tok)) return { kind: 'imm', raw: tok, val: parseInt(tok, 16) };
  return { kind: 'word', raw: tok };
}

// Operand display: prefix = first letter of each word in the type, index/value in
// hexadecimal (matching the source disassembly), e.g.
//   (local-int N)  -> li[N]    (local-ptr N)  -> lp[N]    (local-string N) -> ls[N]
//   (global-int X) -> gi[X]    (global-ptr X) -> gp[X]    (global-string X) -> gs[X]
function opName(op) {
  const LOCAL = { int: 'li', ptr: 'lp', string: 'ls', float: 'lf', 'float-ptr': 'lfp' };
  const GLOBAL = { int: 'gi', ptr: 'gp', string: 'gs', float: 'gf', 'float-ptr': 'gfp' };
  switch (op.kind) {
    case 'local': return `${LOCAL[op.type] || 'l'}[${op.idx.toString(16)}]`;
    case 'global': return `${GLOBAL[op.type] || 'g'}[${op.idx.toString(16)}]`;
    case 'imm': return (op.raw === 'ffffffff') ? '-1' : op.raw;
    case 'label': return op.name;
    case 'str': return op.raw;
    default: return op.raw;
  }
}

// ---------------------------------------------------------------------------
// Symbolic rewriting of known data-processing instructions
// ---------------------------------------------------------------------------
// The first operand is the destination; for value-producing ops we render
//   MNEM d a b  ->  d = <a op b>      e.g. eq a b c -> a = b == c
//   mov d s     ->  d = s
// "full" ops mutate in place (bit-set/bit-reset), rendered specially. Any op whose
// argument count does not match its expected shape is recorded as "unexpected" and
// left verbatim (never rewritten), per the request.

const DATA_OPS = new Map([
  ['mov',      { n: 2, rhs: (a) => `${a[1]}` }],
  ['add',      { n: 3, rhs: (a) => `${a[1]} + ${a[2]}` }],
  ['sub',      { n: 3, rhs: (a) => `${a[1]} - ${a[2]}` }],
  ['mul',      { n: 3, rhs: (a) => `${a[1]} * ${a[2]}` }],
  ['div',      { n: 3, rhs: (a) => `${a[1]} / ${a[2]}` }],
  ['mod',      { n: 3, rhs: (a) => `${a[1]} % ${a[2]}` }],
  ['and',      { n: 3, rhs: (a) => `${a[1]} & ${a[2]}` }],
  ['or',       { n: 3, rhs: (a) => `${a[1]} | ${a[2]}` }],
  ['sar',      { n: 3, rhs: (a) => `${a[1]} >> ${a[2]}` }],
  ['shl',      { n: 3, rhs: (a) => `${a[1]} << ${a[2]}` }],
  ['eq',       { n: 3, rhs: (a) => `${a[1]} == ${a[2]}` }],
  ['ne',       { n: 3, rhs: (a) => `${a[1]} != ${a[2]}` }],
  ['lt',       { n: 3, rhs: (a) => `${a[1]} < ${a[2]}` }],
  ['lte',      { n: 3, rhs: (a) => `${a[1]} <= ${a[2]}` }],
  ['gr',       { n: 3, rhs: (a) => `${a[1]} > ${a[2]}` }],
  ['gre',      { n: 3, rhs: (a) => `${a[1]} >= ${a[2]}` }],
  ['random',   { n: 2, rhs: (a) => `rand() % ${a[1]}` }],
  ['lea',      { n: 2, rhs: (a) => `&${a[1]}` }],
  // bit ops (n are bit indices, verified from sub_42F8B0 / sub_42F920 / sub_42FB40):
  //   bit-set   d b -> d |= (1 << b)          (= 0x135)
  //   bit-reset d b -> d &= ~(1 << b)         (= 0x136)
  //   check-bit d s b -> d = ((1 << b) & s) != 0 (= 0x13F)
  ['bit-set',  { n: 2, full: (a) => `${a[0]} |= (1 << ${a[1]})` }],
  ['bit-reset',{ n: 2, full: (a) => `${a[0]} &= ~(1 << ${a[1]})` }],
  ['check-bit',{ n: 3, rhs: (a) => `((1 << ${a[2]}) & ${a[1]}) != 0` }],
]);

// Record instructions whose shape/arity does not match expectation (kept verbatim).
// Each entry aggregates count + one example (with the file it first appeared in), so
// they can be audited. `CURRENT_FILE` is the file being analysed at the time.
let CURRENT_FILE = null;
const unexpected = new Map();
function recordUnexpected(inst, expected) {
  const key = `${inst.mnem}(${inst.args.length} args, expected ${expected})`;
  const e = unexpected.get(key);
  if (e) { e.count++; }
  else { unexpected.set(key, { count: 1, example: inst.raw, file: CURRENT_FILE }); }
}

const localSlot = (op) => (op.kind === 'local') ? op.idx : null;

// Symbolic form of a straight-line data instruction, or null if it is not a known
// data op / its arity is unexpected (in which case it is recorded and left verbatim).
function symbolicInst(inst) {
  const def = DATA_OPS.get(inst.mnem);
  if (!def) return null;
  if (inst.argsCls.length !== def.n) { recordUnexpected(inst, def.n); return null; }
  const a = inst.argsCls.map(opName);
  return def.full ? def.full(a) : `${a[0]} = ${def.rhs(a)}`;
}

// The right-hand side of a value-producing data op (used when folding an assignment
// into an if/while condition). Returns null for modifier ops / mismatches.
function symbolicRHS(inst) {
  const def = DATA_OPS.get(inst.mnem);
  if (!def || def.full) return null;
  if (inst.argsCls.length !== def.n) { recordUnexpected(inst, def.n); return null; }
  return def.rhs(inst.argsCls.map(opName));
}

// The instruction immediately before a `jcc` that directly assigns the tested
// variable (same local slot), if it is a foldable value-producing data op.
function findFoldable(ctrl, head) {
  if (!head || !head.length) return null;
  const last = head[head.length - 1];
  const def = DATA_OPS.get(last.mnem);
  if (!def || def.full) return null;
  if (last.argsCls.length !== def.n) return null;
  const condSlot = localSlot(ctrl.argsCls[0]);
  const dstSlot = localSlot(last.argsCls[0]);
  if (condSlot == null || dstSlot == null || dstSlot !== condSlot) return null;
  return last;
}

// Statefully strip ALL comments across the whole text, correctly handling
// MULTI-LINE `/* ... */` block comments and `//` line comments, and never touching
// text inside `"..."` strings. AGE scripts use `/* 原文存档（对照用，不参与汇编）... */`
// blocks that wrap MULTIPLE original text lines; a per-line stripper would leak
// those lines into the instruction stream. This pre-pass is the fix.
function stripAllComments(text) {
  let out = '';
  let inStr = false;
  let inBlock = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    const n = text[i + 1];
    if (inBlock) {
      if (c === '*' && n === '/') { inBlock = false; i++; }
      continue;
    }
    if (inStr) {
      out += c;
      if (c === '"') inStr = false;
      continue;
    }
    if (c === '"') { inStr = true; out += c; continue; }
    if (c === '/' && n === '*') { inBlock = true; i++; continue; }
    if (c === '/' && n === '/') { // line comment -> drop to end of line
      while (i < text.length && text[i] !== '\n') i++;
      out += '\n';
      continue;
    }
    out += c;
  }
  return out;
}

function parse(text) {
  text = stripAllComments(text);
  const lines = text.split(/\r?\n/);
  const insts = [];
  const labelOf = new Map(); // label name -> instruction index
  const pendingLabels = [];
  let locals = null;
  for (const raw of lines) {
    const line = raw.trimEnd();
    if (!line.trim()) continue;
    if (isHeaderLine(line)) {
      const m = /^local_vars\s*=\s*\{(.*)\}/.exec(line.trim());
      if (m) locals = m[1].trim().split(/\s+/).filter(Boolean);
      continue;
    }
    const toks = tokenize(line);
    if (toks.length === 0) continue;
    // Collect any leading label definitions on this line.
    let idx = 0;
    while (idx < toks.length && toks[idx].startsWith('label_')) {
      pendingLabels.push(toks[idx]);
      idx++;
    }
    if (idx >= toks.length) continue; // line was only labels
    const mnem = toks[idx];
    const args = toks.slice(idx + 1);
    const iidx = insts.length;
    for (const lab of pendingLabels) labelOf.set(lab, iidx);
    pendingLabels.length = 0;
    insts.push({ mnem, args, raw: line, idx: iidx, argsCls: args.map(classify) });
  }
  // Any labels at EOF with no following instruction map to a sentinel.
  for (const lab of pendingLabels) labelOf.set(lab, insts.length);
  return { locals, insts, labelOf };
}

// ---------------------------------------------------------------------------
// Basic blocks & CFG
// ---------------------------------------------------------------------------

const TERMINATORS = new Set(['jmp', 'jcc', 'call', 'exit', 'exit-script', 'ret', 'call-script']);

function buildBlocks(sc) {
  const n = sc.insts.length;
  const labelTargets = new Set();
  for (const v of sc.labelOf.values()) labelTargets.add(v);

  // Plain label targets must be leaders.
  let leaders = new Set(labelTargets);
  leaders.add(0);

  // Jump/branch targets are leaders (== label targets already).
  // Instruction immediately after a control instruction is a leader (split point).
  for (let i = 0; i < n; i++) {
    const it = sc.insts[i];
    const m = it.mnem;
    if (TERMINATORS.has(m)) {
      leaders.add(i + 1);
      // Record intra-script call targets as leaders too (labels already cover).
    }
    if (m === 'jmp' || m === 'jcc' || m === 'call') {
      for (const a of it.args) {
        if (a.startsWith('label_') && sc.labelOf.has(a)) leaders.add(sc.labelOf.get(a));
      }
    }
  }
  leaders.delete(n); // beyond end
  const sorted = [...leaders].sort((a, b) => a - b);

  // Assign each leader an index; a block owns [leader, nextLeader).
  const blocks = [];
  const blockOfInstr = new Array(n).fill(-1);
  for (let k = 0; k < sorted.length; k++) {
    const start = sorted[k];
    const end = (k + 1 < sorted.length) ? sorted[k + 1] : n;
    const bid = blocks.length;
    const insts = [];
    for (let i = start; i < end; i++) { insts.push(sc.insts[i]); blockOfInstr[i] = bid; }
    const block = { id: bid, start, end, insts, preds: new Set(), succs: new Set(), follow: null, branches: null, labelNames: [] };
    blocks.push(block);
  }
  // Attach label names to the block they point at.
  for (const [name, iidx] of sc.labelOf) {
    if (iidx < n && blockOfInstr[iidx] >= 0) {
      blocks[blockOfInstr[iidx]].labelNames.push(name);
    }
  }

  // Build edges.
  const blockedBy = (iidx) => (iidx >= 0 && iidx < n) ? blockOfInstr[iidx] : null;
  const fallThroughOf = (bid) => {
    const b = blocks[bid];
    if (b.end >= n) return null; // last block, no fall-through
    return blockedBy(b.end);
  };
  for (const b of blocks) {
    const last = b.insts[b.insts.length - 1];
    const m = last.mnem;
    if (m === 'jmp') {
      const t = last.args[0];
      const tgt = sc.labelOf.has(t) ? blockedBy(sc.labelOf.get(t)) : null;
      if (tgt != null) b.succs.add(tgt);
      b.follow = tgt;
    } else if (m === 'jcc') {
      const cond = last.argsCls[0];
      const a = last.args[1];
      const bb = last.args[2];
      const trueTarget = a === 'ffffffff' ? null : (sc.labelOf.has(a) ? blockedBy(sc.labelOf.get(a)) : null);
      const falseTarget = bb === 'ffffffff' ? null : (sc.labelOf.has(bb) ? blockedBy(sc.labelOf.get(bb)) : null);
      const ft = fallThroughOf(b.id);
      const t = trueTarget == null ? ft : trueTarget;
      const f = falseTarget == null ? ft : falseTarget;
      b.branches = { cond, trueBlock: t, falseBlock: f };
      if (t != null) b.succs.add(t);
      if (f != null) b.succs.add(f);
      b.follow = ft;
    } else if (m === 'call') {
      // Intra-script subroutine call: fall-through is the return address;
      // the target is handled as a separate procedure root.
      b.follow = fallThroughOf(b.id);
      if (b.follow != null) b.succs.add(b.follow);
      const t = last.args[0];
      b.callTarget = sc.labelOf.has(t) ? blockedBy(sc.labelOf.get(t)) : null;
    } else if (m === 'exit' || m === 'exit-script' || m === 'ret') {
      b.follow = null;
    } else if (m === 'call-script') {
      // Call another script: it is a statement; fall-through continues.
      b.follow = fallThroughOf(b.id);
      if (b.follow != null) b.succs.add(b.follow);
    } else {
      // Plain block: falls through to the next block.
      b.follow = fallThroughOf(b.id);
      if (b.follow != null) b.succs.add(b.follow);
    }
  }
  // Compute predecessors.
  for (const b of blocks) for (const s of b.succs) blocks[s].preds.add(b.id);
  return { blocks, blockOfInstr };
}

// ---------------------------------------------------------------------------
// Dominators / postdominators
// ---------------------------------------------------------------------------
// Fast (Cooper-Harvey-Kennedy style) dominance with BigInt bitsets. One bit per
// node (index = reverse-postorder position). Intersections are word-level ANDs,
// so this scales well even for multi-thousand-node procedure CFGs.

// Reverse postorder (RPO) of the nodes reachable from `entry` via succsOf.
// In RPO the dominators of a node always appear before it.
function rpo(nodes, entry, succsOf) {
  const inSet = new Set(nodes);
  const visited = new Set([entry]);
  const post = [];
  const stack = [{ node: entry, idx: 0 }];
  while (stack.length) {
    const top = stack[stack.length - 1];
    const succs = succsOf(top.node).filter(s => inSet.has(s));
    if (top.idx < succs.length) {
      const s = succs[top.idx++];
      if (!visited.has(s)) { visited.add(s); stack.push({ node: s, idx: 0 }); }
    } else {
      post.push(top.node);
      stack.pop();
    }
  }
  post.reverse(); // RPO (entry first)
  return post;
}

function computeDominators(nodes, entry, succsOf) {
  const order = rpo(nodes, entry, succsOf);
  const index = new Map();
  order.forEach((id, i) => index.set(id, i));
  const N = order.length;
  const ONE = 1n;
  const ALL = (ONE << BigInt(N)) - 1n;
  const pred = new Map();
  for (const id of order) pred.set(id, []);
  for (const id of order) {
    for (const s of succsOf(id)) if (index.has(s)) pred.get(s).push(id);
  }
  const dom = new Map();
  for (const id of order) dom.set(id, ALL);
  dom.set(entry, ONE << BigInt(index.get(entry)));
  let changed = true;
  while (changed) {
    changed = false;
    for (const id of order) {
      if (id === entry) continue;
      const ps = pred.get(id);
      if (ps.length === 0) continue;
      let nd = dom.get(ps[0]);
      for (let k = 1; k < ps.length; k++) nd &= dom.get(ps[k]);
      nd |= ONE << BigInt(index.get(id));
      if (nd !== dom.get(id)) { dom.set(id, nd); changed = true; }
    }
  }
  return { dom, index, order, N };
}

// Build the dominator map (id -> idom) from a bitset dom result, plus depths.
function computeIdom(domInfo) {
  const { dom, index, order, N } = domInfo;
  const ONE = 1n;
  const idom = new Map();
  const depth = new Map();
  for (const id of order) {
    if (id === order[0]) { depth.set(id, 0); continue; }
    const ownBit = ONE << BigInt(index.get(id));
    let bits = dom.get(id) & ~ownBit; // strict dominators
    let best = order[0];
    let bestDepth = -1;
    while (bits) {
      const low = bits & -bits;
      const i = low.toString(2).length - 1;
      const d = order[i];
      const dd = (depth.get(d) ?? 0);
      if (dd > bestDepth) { bestDepth = dd; best = d; }
      bits ^= low;
    }
    idom.set(id, best);
    depth.set(id, bestDepth + 1);
  }
  return idom;
}

function dominates(domInfo, a, b) {
  // does a dominate b? (bit a set in dom[b])
  if (!domInfo.index.has(a) || !domInfo.index.has(b)) return false;
  return ((domInfo.dom.get(b) >> BigInt(domInfo.index.get(a))) & 1n) !== 0n;
}

// Virtual exit node used during postdominance analysis. Never a real block id.
const EXIT = '__exit__';

// Postdominators: x post-dominates y iff every path y -> exit passes through x.
// Computed by adding a virtual EXIT node (reachable from every terminal block in the
// reversed graph) and computing dominators on the reversed graph rooted at EXIT.
function computePostdominators(nodes, succsOf) {
  const all = [EXIT, ...nodes];
  // Reversed adjacency: original edge u->v becomes v->u. Also EXIT -> terminal(original).
  const rsucc = new Map();
  for (const id of all) rsucc.set(id, []);
  for (const u of nodes) {
    for (const v of succsOf(u)) rsucc.get(v)?.push(u);
    if (succsOf(u).length === 0) rsucc.get(EXIT).push(u); // EXIT -> terminal (reversed)
  }
  const domInfo = computeDominators(all, EXIT, (id) => rsucc.get(id) || []);
  const ipdom = computeIdom(domInfo);
  return { dom: domInfo.dom, ipdom, domInfo };
}

// ---------------------------------------------------------------------------
// Natural loops
// ---------------------------------------------------------------------------

function findNaturalLoops(blocks, entry, succsOf, domInfo) {
  const nodes = [...domInfo.index.keys()]; // procedure members (RPO set)
  const succ = new Map();
  const pred = new Map();
  for (const id of nodes) { succ.set(id, succsOf(id)); }
  for (const id of nodes) {
    if (!pred.has(id)) pred.set(id, []);
    for (const s of succ.get(id)) {
      if (!pred.has(s)) pred.set(s, []);
      pred.get(s).push(id);
    }
  }
  // header -> loop node set
  const loops = new Map();
  for (const u of nodes) {
    for (const v of succ.get(u) || []) {
      if (v === u) {
        // self-loop
        if (!loops.has(v)) loops.set(v, new Set([v]));
        continue;
      }
      // Back edge u->v iff v dominates u (i.e. dom[u] contains v).
      if (dominates(domInfo, v, u)) {
        const loop = new Set([u, v]);
        const work = [u];
        while (work.length) {
          const x = work.pop();
          for (const p of pred.get(x) || []) {
            if (p === v) continue;
            if (!loop.has(p)) { loop.add(p); work.push(p); }
          }
        }
        if (!loops.has(v)) loops.set(v, new Set());
        for (const x of loop) loops.get(v).add(x);
      }
    }
  }
  return loops;
}

