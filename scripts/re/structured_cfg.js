// Distinct exit targets of a loop: flow successors of loop nodes that are outside it.
function loopExits(blocks, loopSet, succsOf) {
  const exits = new Set();
  for (const id of loopSet) {
    for (const s of succsOf(id)) {
      if (!loopSet.has(s)) exits.add(s);
    }
  }
  return exits;
}

// BFS over flow edges from `entry`, stopping at any block in `stops`.
// Returns { nodes:Set, reachable:boolean } where reachable=false means entry is already a stop.
function collectRegion(entry, stops, succsOf) {
  const nodes = new Set();
  if (stops.has(entry)) return { nodes, reachable: false, direct: true };
  const work = [entry];
  nodes.add(entry);
  while (work.length) {
    const x = work.pop();
    for (const s of succsOf(x)) {
      if (stops.has(s) || nodes.has(s)) continue;
      nodes.add(s);
      work.push(s);
    }
  }
  return { nodes, reachable: true };
}

// ---------------------------------------------------------------------------
// Condition inlining (peephole expression reconstruction)
// ---------------------------------------------------------------------------

// Condition for a `jcc`: reference the operand that holds the tested value.
// We do NOT reconstruct/re-inline the boolean expression that computed it — the
// side-effecting instructions (eq/and/... written to that variable) are kept as
// separate statements (two-step form), and the branch test just names the variable.
const condForJcc = (inst) => opName(inst.argsCls[0]);

// Negate a condition (used for the "false branch is the body" / inverted jumps).
// `cond` is already a simple operand name (e.g. `li[2]`); Python-style `not`.
function negCond(cond) {
  return `not ${cond}`;
}

// ---------------------------------------------------------------------------
// Statement rendering
// ---------------------------------------------------------------------------

function renderInst(inst, options) {
  // Known data-processing instructions are rewritten symbolically; everything else
  // (and any unexpected shape) is kept verbatim.
  const sym = symbolicInst(inst);
  if (sym != null) return sym;
  const parts = inst.argsCls.map(opName);
  return `${inst.mnem} ${parts.join(' ')}`.trim();
}

